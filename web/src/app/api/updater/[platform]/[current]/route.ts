import { NextResponse } from 'next/server';
import { promises as fs } from 'fs';
import path from 'path';

/**
 * Tauri 2 auto-updater endpoint.
 *
 * Tauri's `tauri-plugin-updater` calls this on every app launch (and
 * on demand from the JS API). The URL pattern in `tauri.conf.json` is
 *
 *   https://controlcraft.io/api/updater/{{target}}-{{arch}}/{{current_version}}
 *
 * where `{{target}}-{{arch}}` is one of:
 *   - darwin-aarch64
 *   - darwin-x86_64
 *   - windows-x86_64
 *   - linux-x86_64
 *
 * ## Response contract
 *
 * - **204 No Content** — client is up to date.
 * - **200 OK** with JSON — newer version available:
 *   ```
 *   {
 *     "version": "0.2.0",
 *     "notes": "Release highlights…",
 *     "pub_date": "2026-05-26T22:00:00Z",
 *     "url": "https://github.com/owner/repo/releases/download/desktop-v0.2.0/ControlCraft_0.2.0_aarch64.app.tar.gz",
 *     "signature": "<base64 minisign signature from tauri signer sign>"
 *   }
 *   ```
 *
 * ## Manifest source of truth
 *
 * The route reads `web/public/desktop-updates/manifest.json`, which is
 * rewritten by `.github/workflows/desktop-release.yml` on every
 * tag push. The manifest's `platforms` map lets us ship per-target
 * artifacts + signatures generated by Tauri's bundler (signed with
 * `TAURI_SIGNING_PRIVATE_KEY` — pubkey is committed in tauri.conf.json
 * so old installs accept new releases).
 *
 * `?force=1` (handy for QA / forcing a re-download) bypasses the
 * "current === latest" short-circuit so the route returns the
 * manifest even when versions match.
 */

interface PlatformEntry {
  url: string;
  signature: string;
}

interface ReleaseManifest {
  version: string;
  notes: string;
  pub_date: string;
  /** Map of `target-arch` (e.g. `darwin-aarch64`) → asset URL + .sig. */
  platforms: Record<string, PlatformEntry>;
}

const SUPPORTED_PLATFORMS = new Set([
  'darwin-aarch64',
  'darwin-x86_64',
  'windows-x86_64',
  'linux-x86_64',
]);

interface Params {
  params: Promise<{ platform: string; current: string }>;
}

let cached: { mtime: number; data: ReleaseManifest } | null = null;

async function loadManifest(): Promise<ReleaseManifest | null> {
  // Filesystem lookup — works in dev and in production (Next bundles
  // /public verbatim, so the same relative read works in the standalone
  // build output).
  const manifestPath = path.join(
    process.cwd(),
    'public',
    'desktop-updates',
    'manifest.json',
  );
  try {
    const stat = await fs.stat(manifestPath);
    if (cached && cached.mtime === stat.mtimeMs) return cached.data;
    const raw = await fs.readFile(manifestPath, 'utf8');
    const data = JSON.parse(raw) as ReleaseManifest;
    cached = { mtime: stat.mtimeMs, data };
    return data;
  } catch (e) {
    console.warn('[updater] manifest unreadable', { err: String(e) });
    return null;
  }
}

export async function GET(req: Request, { params }: Params) {
  const { platform, current } = await params;
  const url = new URL(req.url);
  const force = url.searchParams.get('force') === '1';

  if (!SUPPORTED_PLATFORMS.has(platform)) {
    return new NextResponse(null, { status: 404 });
  }

  const manifest = await loadManifest();
  if (!manifest) {
    // Manifest missing or invalid — treat as "up to date" so the app
    // never hangs trying to apply a non-existent update.
    return new NextResponse(null, { status: 204 });
  }

  // The client tells us what it's running; if the manifest's latest
  // version matches, send 204 unless `?force=1` was set.
  if (!force && current === manifest.version) {
    return new NextResponse(null, { status: 204 });
  }

  const platformEntry = manifest.platforms[platform];
  if (!platformEntry || !platformEntry.url || !platformEntry.signature) {
    // No artifact for this platform yet — same failsafe as missing manifest.
    return new NextResponse(null, { status: 204 });
  }

  return NextResponse.json(
    {
      version: manifest.version,
      notes: manifest.notes,
      pub_date: manifest.pub_date,
      url: platformEntry.url,
      signature: platformEntry.signature,
    },
    {
      // Updater calls don't benefit from CDN caching — fresh checks
      // matter more than bandwidth, and `Cache-Control: no-store`
      // matches the download endpoint's behavior.
      headers: { 'Cache-Control': 'no-store' },
    },
  );
}
